def q(s):
    return "'" + s.replace("'", "''") + "'"


def positions(region, rows, cols, size, count):
    """영역 안에 rows x cols 격자로 좌석 좌표를 만든다(앞에서부터 count개)."""
    rx, ry, rw, rh = region
    sw, sh = size
    if cols * sw > rw or rows * sh > rh or rows * cols < count:
        raise ValueError("좌석이 구역을 넘치거나 모자랍니다: %s rows=%d cols=%d size=%s" % (region, rows, cols, size))
    gap_x = (rw - cols * sw) / (cols + 1)
    gap_y = (rh - rows * sh) / (rows + 1)
    out = []
    for r in range(rows):
        for c in range(cols):
            if len(out) >= count:
                return out
            out.append((round(rx + gap_x * (c + 1) + sw * c, 2), round(ry + gap_y * (r + 1) + sh * r, 2)))
    return out


def seat_inserts(zone):
    zid, _name, _kind, _price, prefix, stype, count, rows, cols, region, size, cap = zone
    lines = []
    for i, (x, y) in enumerate(positions(region, rows, cols, size, count), start=1):
        label = "%s-%02d" % (prefix, i)
        lines.append(
            "INSERT INTO seat (zone_id, label, pos_x, pos_y, width, height, seat_type, capacity) "
            "VALUES (%d, %s, %s, %s, %s, %s, %s, %d);" % (zid, q(label), x, y, size[0], size[1], q(stype), cap))
    return lines


def seat_updates(zone):
    """V2에서 이미 만들어진 좌석에 좌표를 채운다."""
    zid, _name, _kind, _price, prefix, stype, count, rows, cols, region, size, cap = zone
    lines = []
    for i, (x, y) in enumerate(positions(region, rows, cols, size, count), start=1):
        label = "%s-%02d" % (prefix, i)
        lines.append(
            "UPDATE seat SET pos_x = %s, pos_y = %s, width = %s, height = %s, seat_type = %s, capacity = %d "
            "WHERE zone_id = %d AND label = %s;" % (x, y, size[0], size[1], q(stype), cap, zid, q(label)))
    return lines


